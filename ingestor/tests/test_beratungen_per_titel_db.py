class Kommune:
    """Eine Quelle mit einer Kommune, zwei Gremien, einer anstehenden Sitzung und einer Vorlage wie bei ALLRIS."""

    def __init__(self, storage: DatabaseStorage) -> None:
        self.storage = storage
        self.processor = OParlProcessor()
        self.source_id: uuid.UUID
        self.body_id: uuid.UUID

    async def anlegen(self) -> Kommune:
        self.source_id = await self.storage.upsert_source(f"{BASE}/system", "Musterstadt")
        body = self.processor.process_body(
            {"id": BASE, "type": "https://schema.oparl.org/1.1/Body", "name": "Musterstadt"}, BASE
        )
        self.body_id = await self.storage.upsert_body(body, self.source_id)
        for gremium, name in ((GREMIUM, "Jugendhilfeausschuss"), (RAT, "Rat")):
            daten = {"id": gremium, "type": "https://schema.oparl.org/1.1/Organization", "name": name}
            await self.storage.upsert_organization(self.processor.process_organization(daten, BASE), self.body_id)
        await self.sitzung()
        await self.vorlage()
        return self

    async def sitzung(
        self, *, sitzung: str = MEETING, punkt: str = ITEM, in_tagen: int = 2, **eigenschaften: Any
    ) -> None:
        punkte = [
            {"id": FORMAL, "type": "https://schema.oparl.org/1.1/AgendaItem", "number": "1", "order": 1,
             "name": "Feststellung der Ordnungsgemäßheit der Ladung"},
            {"id": punkt, "type": "https://schema.oparl.org/1.1/AgendaItem", "number": "4.1", "order": 5,
             "name": TITEL.replace(" im ", "  IM ") + " ", **eigenschaften},
        ]  # fmt: skip
        daten = {
            "id": sitzung,
            "type": "https://schema.oparl.org/1.1/Meeting",
            "name": "Sitzung des Jugendhilfeausschusses (1)",
            "start": (datetime.now(UTC) + timedelta(days=in_tagen)).isoformat(),
            "organization": [GREMIUM],
            "agendaItem": punkte,
        }
        await self.storage.upsert_meeting(self.processor.process_meeting(daten, BASE), self.body_id)

    async def vorlage(self, *, paper: str = PAPER, **beratung: Any) -> None:
        daten = {
            "id": paper,
            "type": "https://schema.oparl.org/1.1/Paper",
            "name": TITEL,
            "reference": "VO/2026/5373",
            "consultation": [
                {"id": CONSULTATION if paper == PAPER else f"{paper}/c", "organization": [GREMIUM],
                 "role": "Vorberatung", **beratung},
                {"id": ENTSCHEIDUNG if paper == PAPER else f"{paper}/e", "organization": [RAT],
                 "role": "Entscheidung"},
            ],
        }  # fmt: skip
        await self.storage.upsert_paper(self.processor.process_paper(daten, BASE), self.body_id)

    async def lauf(self) -> dict[str, Any]:
        orchestrator = SyncOrchestrator.__new__(SyncOrchestrator)
        orchestrator.storage = self.storage
        orchestrator.processor = self.processor
        stats: dict[str, Any] = {"consultations": 0}
        await orchestrator._beratungen_per_titel(self.source_id, self.body_id, stats)
        return stats

    async def beratung(self, kennung: str = CONSULTATION) -> OParlConsultation:
        async with self.storage.get_session() as session:
            found = await session.execute(select(OParlConsultation).where(OParlConsultation.external_id == kennung))
            return found.scalar_one()

    async def punkt_id(self, punkt: str = ITEM) -> uuid.UUID:
        async with self.storage.get_session() as session:
            found = await session.execute(select(OParlAgendaItem.id).where(OParlAgendaItem.external_id == punkt))
            return found.scalar_one()

    async def ereignisse(self) -> list[dict[str, Any]]:
        async with self.storage.get_session() as session:
            found = await session.execute(
                text("SELECT payload FROM events_event WHERE type = 'ris.consultation.changed' ORDER BY id")
            )
            return [row[0] for row in found]


@pytest.fixture
async def kommune(storage: DatabaseStorage) -> Kommune:
    return await Kommune(storage).anlegen()


def _bezug(beratung: OParlConsultation) -> tuple[str | None, str | None, bool]:
    return beratung.meeting_external_id, beratung.agenda_item_external_id, beratung.agenda_item_inferred


async def test_zuordnung_ueber_titel_und_gremium(kommune: Kommune) -> None:
    assert _bezug(await kommune.beratung()) == (None, None, False)

    stats = await kommune.lauf()

    beratung = await kommune.beratung()
    assert _bezug(beratung) == (MEETING, ITEM, True)
    assert "agendaItem" not in beratung.raw_json  # Rohdaten bleiben, wie die Quelle sie liefert
    # Die Beratung im Rat tagt nicht in dieser Sitzung
    assert _bezug(await kommune.beratung(ENTSCHEIDUNG)) == (None, None, False)
    assert stats["per_titel"] == {"zugeordnet": 1, "bestaetigt": 0, "zurueckgenommen": 0}
    letztes = (await kommune.ereignisse())[-1]
    assert letztes["agenda_item"] == str(await kommune.punkt_id())
    assert letztes["change"] == "scheduled"

    # Zweiter Lauf und erneuter Abgleich der Vorlage ohne Angaben der Quelle ändern nichts
    anzahl = len(await kommune.ereignisse())
    assert "per_titel" not in await kommune.lauf()
    await kommune.vorlage()
    assert _bezug(await kommune.beratung()) == (MEETING, ITEM, True)
    assert len(await kommune.ereignisse()) == anzahl


async def test_mehrdeutiger_titel_bleibt_offen(kommune: Kommune) -> None:
    await kommune.vorlage(paper=f"{BASE}/papers/2002627")
    assert "per_titel" not in await kommune.lauf()
    assert _bezug(await kommune.beratung()) == (None, None, False)


async def test_punkt_mit_eigener_beratung_und_ferne_sitzung(storage: DatabaseStorage, kommune: Kommune) -> None:
    # Nennt der Punkt eine Beratung, ordnet die Quelle selbst zu
    await kommune.sitzung(consultation=f"{BASE}/consultations/9")
    assert "per_titel" not in await kommune.lauf()
    # Sitzungen außerhalb des Zeitraums bleiben unberührt
    await kommune.sitzung(in_tagen=90)
    assert "per_titel" not in await kommune.lauf()
    assert _bezug(await kommune.beratung()) == (None, None, False)


async def test_abschalten_je_quelle(storage: DatabaseStorage, kommune: Kommune) -> None:
    await storage.set_source_sync_config_value(kommune.source_id, "beratungen_per_titel", False)
    assert "per_titel" not in await kommune.lauf()
    assert _bezug(await kommune.beratung()) == (None, None, False)


async def test_quelle_liefert_ihre_zuordnung_spaeter(kommune: Kommune) -> None:
    await kommune.lauf()
    # Nach der Sitzung nennt die Quelle Sitzung und Punkt: Ihre Angaben gelten, die Markierung fällt weg
    await kommune.vorlage(meeting=MEETING, agendaItem=ITEM)
    assert _bezug(await kommune.beratung()) == (MEETING, ITEM, False)


async def test_quelle_nennt_andere_sitzung(kommune: Kommune) -> None:
    await kommune.lauf()
    # Die Vorlage ist vertagt: Die Quelle nennt eine andere Sitzung, aber (noch) keinen Punkt
    await kommune.vorlage(meeting=SPAETER)
    assert _bezug(await kommune.beratung()) == (SPAETER, None, False)


async def test_zuruecknehmen_wenn_punkt_geloescht(storage: DatabaseStorage, kommune: Kommune) -> None:
    await kommune.lauf()
    async with storage.get_session() as session:
        await session.execute(text("UPDATE oparl_agenda_items SET deleted = true WHERE external_id = :p"), {"p": ITEM})
        await session.commit()

    stats = await kommune.lauf()

    assert stats["per_titel"]["zurueckgenommen"] == 1
    assert _bezug(await kommune.beratung()) == (None, None, False)
    letztes = (await kommune.ereignisse())[-1]
    assert letztes["change"] == "changed" and "agenda_item" not in letztes


async def test_zuruecknehmen_wenn_die_quelle_den_punkt_belegt(kommune: Kommune) -> None:
    await kommune.lauf()
    # Nach der Sitzung ordnet die Quelle dem Punkt eine andere Vorlage zu
    andere = f"{BASE}/papers/3000001"
    daten = {
        "id": andere,
        "type": "https://schema.oparl.org/1.1/Paper",
        "name": "Kindertagesstätte, Ergänzungsvorlage",
        "consultation": [
            {"id": f"{andere}/c", "organization": [GREMIUM], "meeting": MEETING, "agendaItem": ITEM},
        ],
    }
    await kommune.storage.upsert_paper(kommune.processor.process_paper(daten, BASE), kommune.body_id)

    stats = await kommune.lauf()

    assert stats["per_titel"]["zurueckgenommen"] == 1
    assert _bezug(await kommune.beratung()) == (None, None, False)
    assert _bezug(await kommune.beratung(f"{andere}/c")) == (MEETING, ITEM, False)


async def test_bestaetigt_wenn_der_punkt_sie_nennt(kommune: Kommune) -> None:
    await kommune.lauf()
    await kommune.sitzung(consultation=CONSULTATION)

    stats = await kommune.lauf()

    assert stats["per_titel"] == {"zugeordnet": 0, "bestaetigt": 1, "zurueckgenommen": 0}
    assert _bezug(await kommune.beratung()) == (MEETING, ITEM, False)
