"""
Gremiennamen aus dem Kalender (Issue #1505), gegen PostgreSQL: welche Sitzungen gelesen werden und dass nur eine
unveränderte Sitzung ohne Gremium die Angabe bekommt.

Braucht ``INGESTOR_TEST_DATABASE_URL`` (in der CI gesetzt; lokal ohne Datenbank übersprungen). Die Tests legen ein
eigenes Schema aus der Tabellenbeschreibung des Ingestors an und entfernen es wieder.
"""

from __future__ import annotations

import asyncio
import os
import uuid
from collections.abc import AsyncIterator, Iterator
from datetime import UTC, datetime, timedelta

import pytest
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncEngine, AsyncSession, async_sessionmaker, create_async_engine

from src.storage.database import DatabaseStorage
from src.storage.models import Base, OParlBody, OParlMeeting, OParlOrganization, OParlSource
from src.sync.gremien_kalender import ERNEUT_NACH, SCHLUESSEL

DATABASE_URL = os.environ.get("INGESTOR_TEST_DATABASE_URL", "")
SCHEMA = f"ingestor_gremien_{uuid.uuid4().hex[:12]}"
JETZT = datetime(2026, 11, 19, 12, tzinfo=UTC)
GREMIUM = "https://ris.example.org/oparl/organization/152"

pytestmark = pytest.mark.integration


def _engine() -> AsyncEngine:
    url = DATABASE_URL.replace("postgresql://", "postgresql+asyncpg://", 1)
    return create_async_engine(url, connect_args={"server_settings": {"search_path": SCHEMA}})


async def _schema(anlegen: bool) -> None:
    engine = _engine()
    async with engine.begin() as conn:
        if anlegen:
            await conn.execute(text(f'CREATE SCHEMA "{SCHEMA}"'))
            await conn.run_sync(Base.metadata.create_all)
            # Zwischentabelle, die nur Django beschreibt (Gremien einer Sitzung); der Ingestor schreibt sie mit SQL
            await conn.execute(
                text(
                    "CREATE TABLE oparl_meetings_organizations ("
                    " id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    " oparlmeeting_id uuid NOT NULL REFERENCES oparl_meetings (id),"
                    " oparlorganization_id uuid NOT NULL REFERENCES oparl_organizations (id),"
                    " UNIQUE (oparlmeeting_id, oparlorganization_id))"
                )
            )
        else:
            await conn.execute(text(f'DROP SCHEMA IF EXISTS "{SCHEMA}" CASCADE'))
    await engine.dispose()


