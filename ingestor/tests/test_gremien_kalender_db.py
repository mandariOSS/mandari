async def _kommune(storage: DatabaseStorage) -> uuid.UUID:
    async with storage.get_session() as session:
        quelle = OParlSource(name="Stadt", url="https://ris.example.org/oparl/system", sync_config={})
        session.add(quelle)
        await session.flush()
        kommune = OParlBody(external_id="https://ris.example.org/oparl/body/1", source_id=quelle.id, name="Stadt")
        session.add(kommune)
        await session.commit()
        return kommune.id


async def _sitzung(storage: DatabaseStorage, body_id: uuid.UUID, nummer: int, **raw: object) -> uuid.UUID:
    async with storage.get_session() as session:
        sitzung = OParlMeeting(
            external_id=f"https://ris.example.org/oparl/meeting/{nummer}",
            body_id=body_id,
            start=JETZT + timedelta(days=1),
            raw_json={"organization": [GREMIUM], **raw},
        )
        session.add(sitzung)
        await session.commit()
        return sitzung.id


async def _offen(storage: DatabaseStorage, body_id: uuid.UUID) -> dict[str, datetime]:
    zeilen = await storage.get_meetings_ohne_gremium(
        body_id, JETZT - timedelta(days=62), JETZT + timedelta(days=400), JETZT - ERNEUT_NACH, SCHLUESSEL
    )
    return {kennung.rsplit("/", 1)[-1]: stand for _, kennung, _, stand in zeilen}


async def test_liest_nur_offene_sitzungen_ohne_gremium(storage: DatabaseStorage) -> None:
    body_id = await _kommune(storage)
    await _sitzung(storage, body_id, 1)
    await _sitzung(storage, body_id, 2, **{SCHLUESSEL: {"name": "AG Internationales"}})
    await _sitzung(storage, body_id, 3, **{SCHLUESSEL: {"geprueft": (JETZT - timedelta(hours=2)).isoformat()}})
    await _sitzung(storage, body_id, 4, **{SCHLUESSEL: {"geprueft": (JETZT - timedelta(days=2)).isoformat()}})
    zugeordnet = await _sitzung(storage, body_id, 5)
    async with storage.get_session() as session:
        gremium = OParlOrganization(external_id=GREMIUM, body_id=body_id, name="Rat")
        session.add(gremium)
        await session.flush()
        await session.execute(
            text("INSERT INTO oparl_meetings_organizations (oparlmeeting_id, oparlorganization_id) VALUES (:m, :o)"),
            {"m": zugeordnet, "o": gremium.id},
        )
        await session.commit()

    # Ohne Angabe und mit lange zurückliegender Prüfung; nicht: mit Namen, frisch geprüft, mit Gremium im Bestand
    assert set(await _offen(storage, body_id)) == {"1", "4"}


async def test_schreibt_nur_in_die_unveraenderte_sitzung(storage: DatabaseStorage) -> None:
    body_id = await _kommune(storage)
    eins = await _sitzung(storage, body_id, 1)
    zwei = await _sitzung(storage, body_id, 2)
    stand = await _offen(storage, body_id)
    wert = {"name": "AG Internationales", "seite": "https://ris.example.org/si0040.php", "abgerufen": "x"}

    # Ein paralleler Abgleich ändert Sitzung 2 zwischen Lesen und Schreiben
    async with storage.get_session() as session:
        await session.execute(
            text("UPDATE oparl_meetings SET updated_at = now() + interval '1 second' WHERE id = :id"), {"id": zwei}
        )
        await session.commit()

    assert await storage.set_meeting_raw_extension(eins, SCHLUESSEL, wert, stand=stand["1"]) is True
    assert await storage.set_meeting_raw_extension(zwei, SCHLUESSEL, wert, stand=stand["2"]) is False
    # Ein zweiter Lauf mit demselben Stand überschreibt den Namen nicht mit einem Prüfvermerk
    vermerk = {"geprueft": "x", "seite": "https://ris.example.org/si0040.php"}
    assert await storage.set_meeting_raw_extension(eins, SCHLUESSEL, vermerk, stand=stand["1"]) is False
    async with storage.get_session() as session:
        rohdaten = dict((await session.execute(text("SELECT id, raw_json FROM oparl_meetings"))).all())
    assert rohdaten[eins][SCHLUESSEL]["name"] == "AG Internationales" and rohdaten[eins]["organization"] == [GREMIUM]
    assert SCHLUESSEL not in rohdaten[zwei]
    # Der nächste Lauf liest Sitzung 2 wieder, Sitzung 1 nicht mehr
    assert set(await _offen(storage, body_id)) == {"2"}
