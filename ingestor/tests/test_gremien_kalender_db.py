async def _kommune(storage: DatabaseStorage) -> uuid.UUID:
    async with storage.get_session() as session:
        quelle = OParlSource(name="Stadt", url="https://ris.example.org/oparl/system", sync_config={})
        session.add(quelle)
        await session.flush()
        kommune = OParlBody(external_id=KOMMUNE, source_id=quelle.id, name="Stadt")
        session.add(kommune)
        await session.commit()
        return kommune.id


async def _sitzung(
    storage: DatabaseStorage, body_id: uuid.UUID, nummer: int, start: datetime | None = None, **raw: object
) -> uuid.UUID:
    async with storage.get_session() as session:
        sitzung = OParlMeeting(
            external_id=f"https://ris.example.org/oparl/meeting/{nummer}",
            body_id=body_id,
            start=start or JETZT + timedelta(days=1),
            raw_json={"organization": [GREMIUM], **raw},
        )
        session.add(sitzung)
        await session.commit()
        return sitzung.id


async def _offen(storage: DatabaseStorage, body_id: uuid.UUID) -> dict[str, datetime]:
    zeilen = await storage.get_meetings_ohne_gremium(
        [body_id], JETZT - timedelta(days=62), JETZT + timedelta(days=400), JETZT - ERNEUT_NACH, SCHLUESSEL
    )
    return {kennung.rsplit("/", 1)[-1]: stand for _, kennung, _, stand, _ in zeilen}


async def test_liest_nur_offene_sitzungen_ohne_gremium(storage: DatabaseStorage) -> None:
    body_id = await _kommune(storage)
    await _sitzung(storage, body_id, 1)
    await _sitzung(storage, body_id, 2, **{SCHLUESSEL: {"name": "AG Internationales"}})
    await _sitzung(storage, body_id, 3, **{SCHLUESSEL: {"geprueft": (JETZT - timedelta(hours=2)).isoformat()}})
    await _sitzung(storage, body_id, 4, **{SCHLUESSEL: {"geprueft": (JETZT - timedelta(days=2)).isoformat()}})
    zugeordnet = await _sitzung(storage, body_id, 5)
    async with storage.get_session() as session:
        gremium = OParlOrganization(external_id=GREMIUM, body_id=body_id, name="Rat")
        session.add(gremium)
        await session.flush()
        await session.execute(
            text("INSERT INTO oparl_meetings_organizations (oparlmeeting_id, oparlorganization_id) VALUES (:m, :o)"),
            {"m": zugeordnet, "o": gremium.id},
        )
        await session.commit()

    # Ohne Angabe und mit lange zurückliegender Prüfung; nicht: mit Namen, frisch geprüft, mit Gremium im Bestand
    assert set(await _offen(storage, body_id)) == {"1", "4"}
    zeilen = await storage.get_meetings_ohne_gremium(
        [body_id], JETZT - timedelta(days=62), JETZT + timedelta(days=400), JETZT - ERNEUT_NACH, SCHLUESSEL
    )
    # Mit dem Zeitpunkt der letzten Prüfung für die Reihenfolge der Monate
    geprueft = {kennung.rsplit("/", 1)[-1]: zeit for _, kennung, _, _, zeit in zeilen}
    assert geprueft == {"1": None, "4": JETZT - timedelta(days=2)}


async def test_schreibt_nur_in_die_unveraenderte_sitzung(storage: DatabaseStorage) -> None:
    body_id = await _kommune(storage)
    eins = await _sitzung(storage, body_id, 1)
    zwei = await _sitzung(storage, body_id, 2)
    stand = await _offen(storage, body_id)
    wert = {"name": "AG Internationales", "seite": "https://ris.example.org/si0040.php", "abgerufen": "x"}

    # Ein paralleler Abgleich ändert Sitzung 2 zwischen Lesen und Schreiben
    async with storage.get_session() as session:
        await session.execute(
            text("UPDATE oparl_meetings SET updated_at = now() + interval '1 second' WHERE id = :id"), {"id": zwei}
        )
        await session.commit()

    assert await storage.set_meeting_raw_extension(eins, SCHLUESSEL, wert, stand=stand["1"]) is True
    assert await storage.set_meeting_raw_extension(zwei, SCHLUESSEL, wert, stand=stand["2"]) is False
    # Ein zweiter Lauf mit demselben Stand überschreibt den Namen nicht mit einem Prüfvermerk
    vermerk = {"geprueft": "x", "seite": "https://ris.example.org/si0040.php"}
    assert await storage.set_meeting_raw_extension(eins, SCHLUESSEL, vermerk, stand=stand["1"]) is False
    async with storage.get_session() as session:
        rohdaten = dict((await session.execute(text("SELECT id, raw_json FROM oparl_meetings"))).all())
    assert rohdaten[eins][SCHLUESSEL]["name"] == "AG Internationales" and rohdaten[eins]["organization"] == [GREMIUM]
    assert SCHLUESSEL not in rohdaten[zwei]
    # Der nächste Lauf liest Sitzung 2 wieder, Sitzung 1 nicht mehr
    assert set(await _offen(storage, body_id)) == {"2"}


async def test_angabe_uebersteht_den_abgleich_der_sitzung(storage: DatabaseStorage, monkeypatch: Any) -> None:
    """Der volle Abgleich schreibt jede Sitzung neu; Name und Prüfzeitpunkt aus dem Kalender bleiben."""
    assert KALENDER_ANGABE == SCHLUESSEL
    body_id = await _kommune(storage)
    benannt = await _sitzung(storage, body_id, 1, **{SCHLUESSEL: {"name": "AG Internationales"}})
    geprueft = await _sitzung(storage, body_id, 2, **{SCHLUESSEL: {"geprueft": JETZT.isoformat()}})
    ohne = await _sitzung(storage, body_id, 3)

    async def keine_ereignisse(*_: object) -> bool:
        return False

    monkeypatch.setattr(storage, "_events_for", keine_ereignisse)
    verarbeiter = OParlProcessor()
    for nummer in (1, 2, 3):
        daten = {
            "id": f"https://ris.example.org/oparl/meeting/{nummer}",
            "type": "https://schema.oparl.org/1.1/Meeting",
            "name": "Sitzung",
            "organization": [GREMIUM],
            "start": (JETZT + timedelta(days=1)).isoformat(),
        }
        await storage.upsert_meeting(verarbeiter.process_meeting(daten, KOMMUNE), body_id)

    async with storage.get_session() as session:
        rohdaten = dict((await session.execute(text("SELECT id, raw_json FROM oparl_meetings"))).all())
    assert rohdaten[benannt][SCHLUESSEL] == {"name": "AG Internationales"} and rohdaten[benannt]["name"] == "Sitzung"
    assert rohdaten[geprueft][SCHLUESSEL] == {"geprueft": JETZT.isoformat()}
    assert SCHLUESSEL not in rohdaten[ohne] and rohdaten[ohne]["organization"] == [GREMIUM]


async def test_zwei_kalenderlaeufe_mit_vollabgleich_dazwischen(storage: DatabaseStorage, monkeypatch: Any) -> None:
    """
    Acht Monate mit Sitzungen ohne Eintrag im Kalender, zwischen zwei Läufen im Tagesabstand ein Vollabgleich, der jede
    Sitzung neu schreibt: Je Lauf höchstens sechs Seiten, am zweiten Tag kommen die zwei übrigen Monate zuerst dran.
    """
    body_id = await _kommune(storage)
    monate = [(2026 + (11 + i - 1) // 12, (11 + i - 1) % 12 + 1) for i in range(MONATE_JE_LAUF + 2)]
    for i, (jahr, monat) in enumerate(monate):
        await _sitzung(storage, body_id, 2000 + i, start=datetime(jahr, monat, 10, 16, tzinfo=UTC))
    config = KalenderConfig.parse({"sessionnet_kalender": "https://ris.example.org/sessionnet/"})
    assert config is not None
    geladen: list[str] = []

    async def lade(von: datetime, bis: datetime, erneut_ab: datetime) -> list[OhneGremium]:
        zeilen = await storage.get_meetings_ohne_gremium([body_id], von, bis, erneut_ab, SCHLUESSEL)
        return [OhneGremium(id=z[0], external_id=z[1], start=z[2], stand=z[3], geprueft=z[4]) for z in zeilen]

    async def lade_seite(url: str) -> Seite:
        geladen.append(url)
        return Seite(text=KALENDER)  # die Sitzungen stehen nicht darin

    async def speichere(sitzung: OhneGremium, wert: dict[str, str]) -> bool:
        return await storage.set_meeting_raw_extension(sitzung.id, SCHLUESSEL, wert, stand=sitzung.stand)

    def seite(jahr: int, monat: int) -> str:
        return config.monat(jahr, monat)

    erster = await ergaenzen(config, lade, lade_seite, speichere, jetzt=JETZT)
    assert erster.seiten == MONATE_JE_LAUF and geladen == [seite(*m) for m in monate[:MONATE_JE_LAUF]]

    # Vollabgleich: jede Sitzung kommt wie von der Quelle neu herein
    async def keine_ereignisse(*_: object) -> bool:
        return False

    monkeypatch.setattr(storage, "_events_for", keine_ereignisse)
    verarbeiter = OParlProcessor()
    for i, (jahr, monat) in enumerate(monate):
        daten = {
            "id": f"https://ris.example.org/oparl/meeting/{2000 + i}",
            "type": "https://schema.oparl.org/1.1/Meeting",
            "name": "Sitzung",
            "organization": [GREMIUM],
            "start": datetime(jahr, monat, 10, 16, tzinfo=UTC).isoformat(),
        }
        await storage.upsert_meeting(verarbeiter.process_meeting(daten, KOMMUNE), body_id)

    geladen.clear()
    zweiter = await ergaenzen(config, lade, lade_seite, speichere, jetzt=JETZT + ERNEUT_NACH + timedelta(hours=1))
    assert zweiter.seiten == MONATE_JE_LAUF and len(geladen) == MONATE_JE_LAUF
    assert geladen[:2] == [seite(*m) for m in monate[MONATE_JE_LAUF:]]
