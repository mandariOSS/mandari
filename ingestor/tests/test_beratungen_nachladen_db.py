@dataclass
class Antwort:
    data: dict[str, Any] | None = None
    error: str | None = None
    error_kind: str | None = None


class Schnittstelle:
    """more! rubin im Kleinen: Beratung und Vorlage einzeln abrufbar, die alte Kennung liefert eine leere Liste."""

    def __init__(self) -> None:
        self.abgerufen: list[str] = []
        self.objekte: dict[str, dict[str, Any]] = {
            CONSULTATION: {
                "id": CONSULTATION,
                "type": "https://schema.oparl.org/1.0/Consultation",
                "paper": PAPER,
                "agendaItem": ITEM,
                "meeting": MEETING,
                "organization": [f"{GI}/organization/UmweltA"],
                "authoritative": False,
            },
            PAPER: {
                "id": PAPER,
                "type": "https://schema.oparl.org/1.0/Paper",
                "name": "Umweltbericht 2026",
                "reference": "2026/0301",
                "consultation": [
                    {
                        "id": CONSULTATION,
                        "type": "https://schema.oparl.org/1.0/Consultation",
                        "agendaItem": ITEM,
                        "meeting": MEETING,
                    }
                ],
            },
            GONE: {"data": []},
        }

    def deadline_passed(self) -> bool:
        return False

    async def fetch(self, url: str, use_cache: bool = True, skip_wait: bool = False) -> Antwort:
        self.abgerufen.append(url)
        return Antwort(self.objekte[url]) if url in self.objekte else Antwort(error="HTTP 404")


async def _kommune(storage: DatabaseStorage) -> tuple[uuid.UUID, uuid.UUID]:
    processor = OParlProcessor()
    source_id = await storage.upsert_source(f"{GI}/system", "Wissenschaftsstadt Darmstadt")
    body = processor.process_body({"id": BODY, "type": "https://schema.oparl.org/1.0/Body", "name": "Darmstadt"}, BODY)
    body_id = await storage.upsert_body(body, source_id)
    sitzung = {
        "id": MEETING,
        "type": "https://schema.oparl.org/1.0/Meeting",
        "name": "Umweltausschuss",
        "start": (datetime.now(UTC) + timedelta(days=6)).isoformat(),
        "agendaItem": [
            {
                "id": ITEM,
                "type": "https://schema.oparl.org/1.0/AgendaItem",
                "number": "3",
                "consultation": CONSULTATION,
            },
            {"id": LOST, "type": "https://schema.oparl.org/1.0/AgendaItem", "number": "4", "consultation": GONE},
        ],
    }
    await storage.upsert_meeting(processor.process_meeting(sitzung, BODY), body_id)
    return source_id, body_id


async def _lauf(
    storage: DatabaseStorage, source_id: uuid.UUID, body_id: uuid.UUID, api: Schnittstelle
) -> dict[str, Any]:
    orchestrator = SyncOrchestrator.__new__(SyncOrchestrator)
    orchestrator.storage = storage
    orchestrator.processor = OParlProcessor()
    stats: dict[str, Any] = {"consultations": 0, "papers": 0}
    await orchestrator._beratungen_nachladen(api, source_id, body_id, BODY, "Darmstadt", stats)  # type: ignore[arg-type]
    return stats


async def test_beratung_und_vorlage_nachladen_und_scheitern_merken(storage: DatabaseStorage) -> None:
    source_id, body_id = await _kommune(storage)
    api = Schnittstelle()

    stats = await _lauf(storage, source_id, body_id, api)

    assert api.abgerufen == [CONSULTATION, PAPER, GONE] or api.abgerufen == [GONE, CONSULTATION, PAPER]
    assert stats["nachgeladen"]["beratungen"] == 1 and stats["nachgeladen"]["vorlagen"] == 1
    assert stats["consultations"] == 1 and stats["papers"] == 1
    async with storage.get_session() as session:
        beratung = (
            await session.execute(select(OParlConsultation).where(OParlConsultation.external_id == CONSULTATION))
        ).scalar_one()
        quelle = (await session.execute(select(OParlSource).where(OParlSource.id == source_id))).scalar_one()
    assert beratung.paper_id is not None and beratung.agenda_item_external_id == ITEM
    assert set(quelle.sync_config[SYNC_CONFIG_CONSULTATION_FETCHES_KEY]) == {GONE}

    # Zweiter Lauf am selben Tag: nichts mehr zu laden, die gescheiterte Kennung wartet
    api.abgerufen.clear()
    await _lauf(storage, source_id, body_id, api)
    assert api.abgerufen == []


async def test_kontingent_null_schaltet_aus(storage: DatabaseStorage) -> None:
    source_id, body_id = await _kommune(storage)
    await storage.set_source_sync_config_value(source_id, "beratungen_nachladen", 0)
    api = Schnittstelle()
    stats = await _lauf(storage, source_id, body_id, api)
    assert api.abgerufen == [] and "nachgeladen" not in stats
