"""
Vollständigkeit des Änderungsfeeds aus Sicht des Ingestors (Issue #1229, Profil Änderungsfeed von kommParl).

- ``modified`` ändert sich nur mit einem Ereignis: Ein Abgleich ohne inhaltliche Änderung lässt ``oparl_modified`` und
  ``updated_at`` stehen, auch wenn die Quelle ``modified`` neu stempelt. Ob ein Objekt neu zu schreiben ist, entscheidet
  danach der Zeitstempel der Quelle in ``raw_json``.
- Eine Datei, die an einer anderen Vorlage hängt, nennt die frühere (``previous_paper``). Eine Datei an zwei Vorlagen
  oder Sitzungen bleibt an der bisherigen, solange diese sie nennt; kein Wechsel hin und her.

Gegen PostgreSQL (``INGESTOR_TEST_DATABASE_URL``, in der CI gesetzt; lokal ohne Datenbank übersprungen).
"""

from __future__ import annotations

import asyncio
import os
import uuid
from collections.abc import AsyncIterator, Iterator
from datetime import UTC, datetime
from typing import Any

import pytest
from sqlalchemy import select, text
from sqlalchemy.ext.asyncio import AsyncEngine, AsyncSession, async_sessionmaker, create_async_engine

from src.storage.database import DatabaseStorage
from src.storage.models import Base, OParlFile, OParlMeeting, OParlPaper
from src.sync.orchestrator import SyncOrchestrator
from src.sync.processor import OParlProcessor

OPARL = "https://schema.oparl.org/1.1/"
BASE = "https://oparl.stadt.example/bodies/0001"
KOMMUNE = BASE
VORLAGE_A = f"{BASE}/papers/1"
VORLAGE_B = f"{BASE}/papers/2"
DATEI = f"{BASE}/files/1"
SITZUNG_1 = f"{BASE}/meetings/1"
SITZUNG_2 = f"{BASE}/meetings/2"
T1 = "2026-11-01T10:00:00+01:00"
T2 = "2026-11-20T10:00:00+01:00"

DATABASE_URL = os.environ.get("INGESTOR_TEST_DATABASE_URL", "")
SCHEMA = f"ingestor_feed_{uuid.uuid4().hex[:12]}"


def _datei(**felder: Any) -> dict[str, Any]:
    daten: dict[str, Any] = {
        "id": DATEI,
        "type": f"{OPARL}File",
        "name": "Begründung",
        "fileName": "begruendung.pdf",
        "accessUrl": f"{DATEI}/begruendung.pdf",
    }
    daten.update(felder)
    return daten


def _vorlage(kennung: str, *dateien: dict[str, Any], modified: str = T1, **felder: Any) -> dict[str, Any]:
    daten: dict[str, Any] = {
        "id": kennung,
        "type": f"{OPARL}Paper",
        "name": f"Vorlage {kennung.rsplit('/', 1)[1]}",
        "reference": f"V/{kennung.rsplit('/', 1)[1]}",
        "auxiliaryFile": list(dateien),
        "modified": modified,
    }
    daten.update(felder)
    return daten


def _engine() -> AsyncEngine:
    url = DATABASE_URL.replace("postgresql://", "postgresql+asyncpg://", 1)
    return create_async_engine(url, connect_args={"server_settings": {"search_path": SCHEMA}})


async def _schema(anlegen: bool) -> None:
    engine = _engine()
    async with engine.begin() as conn:
        if not anlegen:
            await conn.execute(text(f'DROP SCHEMA IF EXISTS "{SCHEMA}" CASCADE'))
        else:
            await conn.execute(text(f'CREATE SCHEMA "{SCHEMA}"'))
            await conn.run_sync(Base.metadata.create_all)
            # Was in der Installation die Django-Migration der Ereignistechnik anlegt (test_events_journal.py)
            await conn.execute(
                text(
                    "ALTER TABLE events_event"
                    " ADD COLUMN seq bigint NULL UNIQUE,"
                    " ADD COLUMN recorded_at timestamptz NOT NULL DEFAULT now(),"
                    " ADD COLUMN xid xid8 NOT NULL DEFAULT pg_current_xact_id()"
                )
            )
            # Zwischentabellen, die nur Django beschreibt; der Ingestor schreibt sie mit SQL
            await conn.execute(
                text(
                    "CREATE TABLE oparl_meetings_organizations ("
                    " id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    " oparlmeeting_id uuid NOT NULL REFERENCES oparl_meetings (id),"
                    " oparlorganization_id uuid NOT NULL REFERENCES oparl_organizations (id),"
                    " UNIQUE (oparlmeeting_id, oparlorganization_id))"
                )
            )
            await conn.execute(
                text(
                    "CREATE TABLE oparl_papers_locations ("
                    " id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
                    " oparlpaper_id uuid NOT NULL REFERENCES oparl_papers (id),"
                    " oparllocation_id uuid NOT NULL REFERENCES oparl_locations (id),"
                    " UNIQUE (oparlpaper_id, oparllocation_id))"
                )
            )
    await engine.dispose()


@pytest.fixture(scope="module")
def schema() -> Iterator[None]:
    if not DATABASE_URL:
        if os.environ.get("CI"):
            pytest.fail("INGESTOR_TEST_DATABASE_URL fehlt: In der CI müssen diese Tests laufen.")
        pytest.skip("braucht PostgreSQL (INGESTOR_TEST_DATABASE_URL)")
    asyncio.run(_schema(anlegen=True))
    yield
    asyncio.run(_schema(anlegen=False))


@pytest.fixture(params=[False, True], ids=["ohne_ereignisse", "mit_ereignissen"])
async def speicher(schema: None, request: pytest.FixtureRequest) -> AsyncIterator[DatabaseStorage]:
    storage = DatabaseStorage(
        DATABASE_URL.replace("postgresql://", "postgresql+asyncpg://", 1), events_enabled=request.param
    )
    await storage._engine.dispose()
    storage._engine = _engine()
    storage._session_factory = async_sessionmaker(storage._engine, class_=AsyncSession, expire_on_commit=False)
    async with storage._engine.begin() as conn:
        tabellen = ", ".join(f'"{tabelle.name}"' for tabelle in Base.metadata.sorted_tables)
        await conn.execute(text(f"TRUNCATE {tabellen}, oparl_meetings_organizations, oparl_papers_locations CASCADE"))
    yield storage
    await storage.close()


async def _abgleich(storage: DatabaseStorage) -> tuple[SyncOrchestrator, uuid.UUID]:
    orchestrator = SyncOrchestrator.__new__(SyncOrchestrator)
    orchestrator.storage = storage
    orchestrator.processor = OParlProcessor(storage.id_bases)
    source_id = await storage.upsert_source("https://oparl.stadt.example/system", "Musterstadt")
    body = OParlProcessor().process_body({"id": KOMMUNE, "type": f"{OPARL}Body", "name": "Musterstadt"}, KOMMUNE)
    return orchestrator, await storage.upsert_body(body, source_id)


async def _speichern(orchestrator: SyncOrchestrator, kommune: uuid.UUID, daten: dict[str, Any]) -> None:
    objekt = orchestrator.processor.process(daten, KOMMUNE)
    assert objekt is not None
    assert await orchestrator._store_entity(objekt, kommune, "paper") is True


async def _stempel(storage: DatabaseStorage, kennung: str) -> tuple[datetime | None, datetime]:
    async with storage.get_session() as session:
        zeile = (
            await session.execute(
                select(OParlPaper.oparl_modified, OParlPaper.updated_at).where(OParlPaper.external_id == kennung)
            )
        ).one()
        return zeile[0], zeile[1]


async def _ereignisse(storage: DatabaseStorage, typ: str) -> list[dict[str, Any]]:
    async with storage.get_session() as session:
        zeilen = await session.execute(
            text("SELECT payload FROM events_event WHERE type = :typ ORDER BY id"), {"typ": typ}
        )
        return [zeile[0] for zeile in zeilen]


async def _vorlage_der_datei(storage: DatabaseStorage) -> uuid.UUID | None:
    async with storage.get_session() as session:
        return (await session.execute(select(OParlFile.paper_id).where(OParlFile.external_id == DATEI))).scalar_one()


async def _kennung(storage: DatabaseStorage, kennung: str) -> uuid.UUID:
    async with storage.get_session() as session:
        return (await session.execute(select(OParlPaper.id).where(OParlPaper.external_id == kennung))).scalar_one()


@pytest.mark.integration
async def test_neuer_stempel_der_quelle_ohne_aenderung_laesst_modified_stehen(speicher: DatabaseStorage) -> None:
    orchestrator, kommune = await _abgleich(speicher)
    await _speichern(orchestrator, kommune, _vorlage(VORLAGE_A, modified=T1))
    vorher = await _stempel(speicher, VORLAGE_A)

    await _speichern(orchestrator, kommune, _vorlage(VORLAGE_A, modified=T2))

    nachher = await _stempel(speicher, VORLAGE_A)
    neu = datetime.fromisoformat(T2).astimezone(UTC)
    if speicher.events_enabled:
        # Kein Ereignis, also auch kein neues ``modified`` in der Schnittstelle
        assert nachher == vorher
        assert [n["paper"] for n in await _ereignisse(speicher, "ris.paper.released")] == [
            str(await _kennung(speicher, VORLAGE_A))
        ]
        assert await _ereignisse(speicher, "ris.paper.changed") == []
    else:
        assert nachher[0] == neu
    # Ob neu zu schreiben ist, entscheidet der Stand der Quelle: Der nächste Lauf überspringt das Objekt
    stand = await speicher.batch_check_entities_exist("paper", [VORLAGE_A])
    assert stand[VORLAGE_A] == neu


@pytest.mark.integration
async def test_inhaltliche_aenderung_schreibt_modified_fort(speicher: DatabaseStorage) -> None:
    orchestrator, kommune = await _abgleich(speicher)
    await _speichern(orchestrator, kommune, _vorlage(VORLAGE_A, modified=T1))

    await _speichern(orchestrator, kommune, _vorlage(VORLAGE_A, modified=T2, name="Radweg, geändert"))

    assert (await _stempel(speicher, VORLAGE_A))[0] == datetime.fromisoformat(T2).astimezone(UTC)
    if speicher.events_enabled:
        assert [n["changed"] for n in await _ereignisse(speicher, "ris.paper.changed")] == [["name"]]


@pytest.mark.integration
async def test_datei_an_zwei_vorlagen_bleibt_an_der_ersten(speicher: DatabaseStorage) -> None:
    orchestrator, kommune = await _abgleich(speicher)
    await _speichern(orchestrator, kommune, _vorlage(VORLAGE_A, _datei()))
    erste = await _kennung(speicher, VORLAGE_A)

    # Ein zweiter Vollabgleich mit beiden Vorlagen: kein Wechsel, kein Ereignis zur Datei
    for _lauf in range(2):
        await _speichern(orchestrator, kommune, _vorlage(VORLAGE_B, _datei()))
        await _speichern(orchestrator, kommune, _vorlage(VORLAGE_A, _datei()))

    assert await _vorlage_der_datei(speicher) == erste
    if speicher.events_enabled:
        anlagen = await _ereignisse(speicher, "ris.file.changed")
        assert [(n["change"], n.get("paper"), n.get("previous_paper")) for n in anlagen] == [
            ("added", str(erste), None)
        ]


@pytest.mark.integration
async def test_datei_wechselt_die_vorlage_und_nennt_die_fruehere(speicher: DatabaseStorage) -> None:
    orchestrator, kommune = await _abgleich(speicher)
    await _speichern(orchestrator, kommune, _vorlage(VORLAGE_A, _datei()))
    erste = await _kennung(speicher, VORLAGE_A)

    # Die Quelle hängt die Datei um: Die erste Vorlage nennt sie nicht mehr
    await _speichern(orchestrator, kommune, _vorlage(VORLAGE_A, modified=T2))
    await _speichern(orchestrator, kommune, _vorlage(VORLAGE_B, _datei()))
    zweite = await _kennung(speicher, VORLAGE_B)

    assert await _vorlage_der_datei(speicher) == zweite
    if speicher.events_enabled:
        letzte = (await _ereignisse(speicher, "ris.file.changed"))[-1]
        assert (letzte["change"], letzte["paper"], letzte["previous_paper"]) == ("added", str(zweite), str(erste))


@pytest.mark.integration
async def test_niederschrift_als_anlage_der_naechsten_sitzung_bleibt(speicher: DatabaseStorage) -> None:
    """Die Niederschrift der ersten Sitzung steht als Anlage in der zweiten: Sie bleibt bei der ersten, ohne Wechsel."""
    orchestrator, kommune = await _abgleich(speicher)
    erste = {"id": SITZUNG_1, "type": f"{OPARL}Meeting", "name": "Rat", "resultsProtocol": _datei()}
    zweite = {"id": SITZUNG_2, "type": f"{OPARL}Meeting", "name": "Rat", "auxiliaryFile": [_datei()]}

    for _lauf in range(2):
        for sitzung in (erste, zweite):
            objekt = orchestrator.processor.process(sitzung, KOMMUNE)
            assert objekt is not None
            assert await orchestrator._store_entity(objekt, kommune, "meeting") is True

    async with speicher.get_session() as session:
        bei = (await session.execute(select(OParlFile.meeting_id).where(OParlFile.external_id == DATEI))).scalar_one()
        kennung = (
            await session.execute(select(OParlMeeting.id).where(OParlMeeting.external_id == SITZUNG_1))
        ).scalar_one()
    assert bei == kennung
    if speicher.events_enabled:
        anlagen = await _ereignisse(speicher, "ris.file.changed")
        assert [(n["change"], n.get("meeting"), n.get("previous_meeting")) for n in anlagen] == [
            ("added", str(kennung), None)
        ]
