"""
Rückverweis Tagesordnungspunkt → Beratung (Issue #1523), gegen PostgreSQL.

SD.NET RIM setzt ``agendaItem`` einer Beratung erst, wenn der Tagesordnungspunkt angelegt wird, und ändert dabei
``modified`` nicht. Eine vorher gespeicherte Beratung bliebe ohne Punkt, obwohl der Punkt sie nennt
(``AgendaItem.consultation``). Geprüft: Rückverweis aus dem Punkt (eingebettet in der Sitzung), aus der Beratung
(eingebettet in der Vorlage, Sitzung bekannt), vorhandene Bezüge und fremde Quellen bleiben unberührt, Ereignis wie
beim Upsert, Nachziehen des Bestands idempotent mit Probelauf.

Braucht ``INGESTOR_TEST_DATABASE_URL`` (in der CI gesetzt; lokal ohne Datenbank übersprungen). Die Tests legen ein
eigenes Schema aus der Tabellenbeschreibung des Ingestors an und entfernen es wieder.
"""

