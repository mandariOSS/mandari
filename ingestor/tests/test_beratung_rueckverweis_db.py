class Quelle:
    """Eine Quelle mit einer Kommune; schreibt Objekte wie der Abgleich."""

    def __init__(self, storage: DatabaseStorage, basis: str = BASE) -> None:
        self.storage = storage
        self.basis = basis
        self.processor = OParlProcessor()
        self.body_id: uuid.UUID

    async def anlegen(self, name: str = "Musterstadt") -> Quelle:
        source_id = await self.storage.upsert_source(f"{self.basis}/system", name)
        body = self.processor.process_body(
            {"id": self.basis, "type": "https://schema.oparl.org/1.1/Body", "name": name}, self.basis
        )
        self.body_id = await self.storage.upsert_body(body, source_id)
        return self

    async def sitzung_mit_punkt(
        self, beratung: str | dict[str, Any] | None = CONSULTATION, punkt: str = ITEM
    ) -> uuid.UUID:
        top: dict[str, Any] = {
            "id": punkt,
            "type": "https://schema.oparl.org/1.1/AgendaItem",
            "number": "4.1",
            "name": "Öffentliche Trinkbrunnen",
            "order": 1,
        }
        if beratung is not None:
            top["consultation"] = beratung
        daten = {
            "id": MEETING,
            "type": "https://schema.oparl.org/1.1/Meeting",
            "name": "Rat",
            "start": "2026-11-26T17:00:00+01:00",
            "modified": "2026-11-20T12:25:26+01:00",
            "agendaItem": [top],
        }
        return await self.storage.upsert_meeting(self.processor.process_meeting(daten, self.basis), self.body_id)

    async def vorlage_mit_beratung(self, **beratung: Any) -> uuid.UUID:
        eingebettet = {
            "id": CONSULTATION,
            "type": "https://schema.oparl.org/1.1/Consultation",
            "meeting": MEETING,
            "organization": [f"{BASE}/organization/1-15"],
            "modified": "2026-10-13T09:24:59+02:00",
            **beratung,
        }
        daten = {
            "id": PAPER,
            "type": "https://schema.oparl.org/1.1/Paper",
            "name": "Öffentliche Trinkbrunnen in Hamm",
            "modified": "2026-10-13T09:24:59+02:00",
            "consultation": [eingebettet],
        }
        return await self.storage.upsert_paper(self.processor.process_paper(daten, self.basis), self.body_id)

    async def beratung(self) -> OParlConsultation:
        async with self.storage.get_session() as session:
            found = await session.execute(
                select(OParlConsultation).where(OParlConsultation.external_id == CONSULTATION)
            )
            return found.scalar_one()

    async def punkt_id(self, punkt: str = ITEM) -> uuid.UUID:
        async with self.storage.get_session() as session:
            found = await session.execute(select(OParlAgendaItem.id).where(OParlAgendaItem.external_id == punkt))
            return found.scalar_one()

    async def ereignisse(self) -> list[dict[str, Any]]:
        async with self.storage.get_session() as session:
            found = await session.execute(
                text("SELECT type, payload FROM events_event WHERE type = 'ris.consultation.changed' ORDER BY id")
            )
            return [dict(row._mapping) for row in found]


@pytest.fixture
async def quelle(storage: DatabaseStorage) -> Quelle:
    return await Quelle(storage).anlegen()


async def test_punkt_traegt_sich_an_der_beratung_ein(quelle: Quelle) -> None:
    """Beratung zuerst (in der Vorlage, ohne Punkt), dann die Sitzung mit dem Punkt, der sie nennt."""
    await quelle.vorlage_mit_beratung(meeting=None)
    assert (await quelle.beratung()).agenda_item_external_id is None

    await quelle.sitzung_mit_punkt()

    beratung = await quelle.beratung()
    assert beratung.agenda_item_external_id == ITEM
    assert beratung.meeting_external_id == MEETING  # Sitzung des Punkts, weil die Beratung keine nannte
    assert "agendaItem" not in beratung.raw_json  # Rohdaten bleiben, wie die Quelle sie liefert
    letztes = (await quelle.ereignisse())[-1]
    assert letztes["payload"]["agenda_item"] == str(await quelle.punkt_id())
    assert letztes["payload"]["change"] in {"changed", "scheduled"}

    # Erneutes Speichern ändert nichts und meldet nichts
    anzahl = len(await quelle.ereignisse())
    await quelle.sitzung_mit_punkt()
    await quelle.vorlage_mit_beratung(meeting=None)
    assert (await quelle.beratung()).agenda_item_external_id == ITEM
    assert len(await quelle.ereignisse()) == anzahl


async def test_beratung_findet_den_punkt_ihrer_sitzung(quelle: Quelle) -> None:
    """Sitzung mit Punkt zuerst, dann die Beratung ohne ``agendaItem``, aber mit ``meeting``."""
    await quelle.sitzung_mit_punkt()
    await quelle.vorlage_mit_beratung()

    assert (await quelle.beratung()).agenda_item_external_id == ITEM
    ereignis = (await quelle.ereignisse())[-1]
    assert ereignis["payload"]["change"] == "added"
    assert ereignis["payload"]["agenda_item"] == str(await quelle.punkt_id())


