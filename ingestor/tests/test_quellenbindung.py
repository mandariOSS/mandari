async def _bestand_b(storage: DatabaseStorage) -> dict[str, Any]:
    """Was von Stadt B im Bestand steht (Name, Kommune, Markierung, Zuordnungen)."""
    werte: dict[str, Any] = {}
    for model, art, nummer in (
        (OParlPaper, "paper", 1),
        (OParlPaper, "paper", 2),
        (OParlPaper, "paper", 3),
        (OParlMeeting, "meeting", 1),
        (OParlOrganization, "organization", 1),
        (OParlPerson, "person", 1),
        (OParlAgendaItem, "agendaitem", 1),
    ):
        zeile = await _zeile(storage, model, f"{B}/{art}/{nummer}")
        assert zeile is not None
        werte[f"{art}/{nummer}"] = {
            "name": zeile.name,
            "deleted": zeile.deleted,
            "modified": zeile.oparl_modified,
            "body": getattr(zeile, "body_id", None) or getattr(zeile, "meeting_id", None),
            **({"number": zeile.number} if model is OParlAgendaItem else {}),
        }
    kommune = await _zeile(storage, OParlBody, KOMMUNE_B)
    werte["body"] = {
        "name": kommune.name,
        "source": kommune.source_id,
        "paper_list_url": kommune.paper_list_url,
        "is_listed": kommune.is_listed,
    }
    werte["tagesordnung"] = await _anzahl(
        storage,
        "SELECT count(*) FROM oparl_agenda_items i JOIN oparl_meetings m ON m.id = i.meeting_id"
        " WHERE m.external_id = :sitzung",
        sitzung=f"{B}/meeting/1",
    )
    werte["dateien"] = await _anzahl(
        storage,
        "SELECT count(*) FROM oparl_files f JOIN oparl_papers p ON p.id = f.paper_id WHERE p.external_id = :vorlage",
        vorlage=f"{B}/paper/3",
    )
    werte["objekte"] = {
        tabelle: await _anzahl(
            storage,
            f"SELECT count(*) FROM {tabelle} WHERE body_id = :body",  # noqa: S608 - feste Tabellennamen
            body=kommune.id,
        )
        for tabelle in ("oparl_papers", "oparl_meetings", "oparl_files", "oparl_persons", "oparl_organizations")
    }
    return werte


async def test_abgleich_einer_quelle_laesst_objekte_anderer_quellen_unveraendert(
    speicher: DatabaseStorage, netz: Callable[..., None]
) -> None:
    stadt_b, stadt_a = _stadt_b(), _stadt_a()
    netz(stadt_b, stadt_a)

    ergebnis_b = await _abgleich(speicher, stadt_b, full=True)
    assert ergebnis_b.success and ergebnis_b.errors == []
    # Hinterlegte Kopfzeilen für den Dokumentabruf gelten nur für Dateien von Stadt B
    async with speicher.get_session() as session:
        await session.execute(
            update(OParlSource)
            .where(OParlSource.url == stadt_b.adresse)
            .values(sync_config={"download_headers": {"Cookie": "sitzung=nur-fuer-b"}})
        )
        await session.execute(update(OParlBody).where(OParlBody.external_id == KOMMUNE_B).values(is_listed=True))
        await session.commit()
    vorher = await _bestand_b(speicher)

    # Erst inkrementell (neueres modified), dann voll: Beide Zweige schreiben jedes Objekt
    inkrementell = await _abgleich(speicher, stadt_a, full=False)
    voll = await _abgleich(speicher, stadt_a, full=True)

    assert await _bestand_b(speicher) == vorher
    # Was Quelle A sonst liefert, steht im Bestand, unter ihrer eigenen Kommune
    kommune_a = await _zeile(speicher, OParlBody, KOMMUNE_A)
    for model, kennung in (
        (OParlPaper, f"{A}/paper/1"),
        (OParlMeeting, f"{A}/meeting/1"),
        (OParlFile, f"{A}/file/1"),
    ):
        zeile = await _zeile(speicher, model, kennung)
        assert zeile is not None and zeile.body_id == kommune_a.id
    punkt = await _zeile(speicher, OParlAgendaItem, f"{A}/agendaitem/2")
    assert punkt is not None and punkt.meeting_id == (await _zeile(speicher, OParlMeeting, f"{A}/meeting/1")).id
    # Der Punkt in der Sitzung von Stadt B und die Zuordnung der Datei zu ihrer Vorlage fehlen
    assert await _zeile(speicher, OParlAgendaItem, f"{A}/agendaitem/1") is None
    datei = await _zeile(speicher, OParlFile, f"{A}/file/1")
    assert datei.paper_id is None
    # Keine Datei, deren Adresse Quelle A bestimmt, läuft mit den Kopfzeilen von Stadt B
    async with speicher.get_session() as session:
        dateien = (await session.execute(select(OParlFile.body_id, OParlFile.access_url))).all()
    for body_id, adresse in dateien:
        if adresse and adresse.startswith(A):
            assert await speicher.get_download_headers_for_body(body_id) == {}

    for ergebnis in (inkrementell, voll):
        assert ergebnis.success
        assert ergebnis.foreign == {
            "agendaitem": 1,
            "consultation (Verweis)": 1,
            "meeting (Verweis)": 1,
            "organization": 1,
            "paper": 1,
            "paper (Löschung)": 1,
            "paper (Verweis)": 1,
            "person": 1,
        }


async def test_kommune_einer_anderen_quelle_wird_nicht_uebernommen(
    speicher: DatabaseStorage, netz: Callable[..., None]
) -> None:
    stadt_b, stadt_a = _stadt_b(), _stadt_a()
    netz(stadt_b, stadt_a)
    assert (await _abgleich(speicher, stadt_b, full=True)).success
    async with speicher.get_session() as session:
        await session.execute(update(OParlBody).where(OParlBody.external_id == KOMMUNE_B).values(is_listed=True))
        await session.commit()
    vorher = await _bestand_b(speicher)

    # Das Body-Objekt der Quelle A nennt die Kennung der Kommune B
    stadt_a.kennung = KOMMUNE_B
    stadt_a.name = "Von A übernommen"
    stadt_a.listen["paper"].append(objekt(A, "paper", 9, name="Neue Vorlage von A"))
    for full in (False, True):
        ergebnis = await _abgleich(speicher, stadt_a, full=full)
        assert any(KOMMUNE_B in fehler for fehler in ergebnis.errors)

    assert await _bestand_b(speicher) == vorher
    assert await _zeile(speicher, OParlPaper, f"{A}/paper/9") is None
    # Die Quelle A hat keine Kommune bekommen
    async with speicher.get_session() as session:
        quelle_a = (
            await session.execute(select(OParlSource.id).where(OParlSource.url == stadt_a.adresse))
        ).scalar_one()
        assert (await session.execute(select(OParlBody).where(OParlBody.source_id == quelle_a))).first() is None


