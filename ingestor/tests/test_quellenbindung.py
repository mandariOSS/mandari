async def test_kommunen_derselben_quelle_teilen_sich_objekte(speicher: DatabaseStorage) -> None:
    """Eine Quelle mit zwei Kommunen (Kreis und Gemeinde): Objekte, die beide nennen, bleiben schreibbar."""
    zwei = Bestand(speicher)
    kreis = await zwei.kommune_anlegen(B, quelle=f"{B}/system", nummer=1)
    gemeinde = await zwei.kommune_anlegen(B, quelle=f"{B}/system", nummer=2)
    gemeinde_kennung = f"{B}/body/2"
    for art in ("organization", "person", "meeting", "paper", "location", "file"):
        await zwei.schreiben(art, ARTEN_B[art](), kreis, KOMMUNE_B)

    # Die zweite Kommune nennt dieselben Objekte: Sie werden geschrieben, die Kommune der Zeile bleibt
    for art in ("organization", "person", "meeting", "paper", "location", "file"):
        daten = ARTEN_B[art]()
        daten.update(modified=SPAETER)
        for feld in ("name", "description"):
            if feld in daten:
                daten[feld] = "Aus der Gemeinde"
        await zwei.schreiben(art, daten, gemeinde, gemeinde_kennung)
        zeile = await _zeile(speicher, MODELLE[art], f"{B}/{art}/1")
        assert zeile.body_id == kreis
        assert (getattr(zeile, "name", None) or getattr(zeile, "description", None)) == "Aus der Gemeinde"

    assert await speicher.get_meeting_uuid(f"{B}/meeting/1", gemeinde) is not None
    assert await speicher.get_person_ids_by_external_ids([f"{B}/person/1"], gemeinde) != {}
    # Neu und noch einmal (Konflikt auf der eigenen Zeile): Sitzung und Gremium gehören der Kommune des Kreises
    mitgliedschaft = objekt(B, "membership", 2, person=f"{B}/person/1", organization=f"{B}/organization/1")
    punkt = objekt(B, "agendaitem", 2, meeting=f"{B}/meeting/1")
    for kommune, kennung in ((gemeinde, gemeinde_kennung), (kreis, KOMMUNE_B), (gemeinde, gemeinde_kennung)):
        assert await zwei.schreiben("membership", mitgliedschaft, kommune, kennung) is not None
        assert await zwei.schreiben("agendaitem", punkt, kommune, kennung) is not None
    assert await speicher.mark_entity_deleted("paper", f"{B}/paper/1", body_id=gemeinde) is not None
    assert await speicher.mark_entity_deleted("agendaitem", f"{B}/agendaitem/2", body_id=gemeinde) is not None
    assert await speicher.mark_entity_deleted("membership", f"{B}/membership/2", body_id=gemeinde) is not None


