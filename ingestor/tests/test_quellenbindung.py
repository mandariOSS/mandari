def _fremd(art: str) -> dict[str, Any]:
    """Objekt der Quelle A mit der Kennung des Objekts von Stadt B; Bezüge auf Objekte von A."""
    daten = ARTEN_B[art]()
    daten.update(modified=SPAETER, deleted=False)
    for feld in ("name", "description", "role"):
        if feld in daten:
            daten[feld] = "Von A überschrieben"
    if art == "membership":
        daten.update(person=f"{A}/person/1", organization=f"{A}/organization/1", role="Von A überschrieben")
    if art == "agendaitem":
        daten["meeting"] = f"{A}/meeting/1"
    if art == "file":
        daten["accessUrl"] = f"{A}/datei/1"
    if art == "consultation":
        daten["paper"] = f"{A}/paper/1"
    return daten


