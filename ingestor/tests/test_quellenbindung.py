def objekt(basis: str, art: str, nummer: int | str, **felder: Any) -> dict[str, Any]:
    typ = {"agendaitem": "AgendaItem", "legislativeterm": "LegislativeTerm"}.get(art, art.capitalize())
    daten: dict[str, Any] = {"id": f"{basis}/{art}/{nummer}", "type": f"{OPARL}{typ}", "modified": FRUEHER}
    daten.update(felder)
    return daten


#: Feld der Liste im Body-Objekt (``OParlProcessor.process_body``)
LISTENFELD = {"agendaitem": "agendaItem"}


class Ris:
    """OParl-Schnittstelle einer Quelle mit einer Kommune; Listen ohne Filter und auf einer Seite."""

    def __init__(self, basis: str, name: str) -> None:
        self.basis = basis
        self.adresse = f"{basis}/body/1"
        #: Kennung, die das Body-Objekt unter ``adresse`` nennt
        self.kennung = self.adresse
        self.name = name
        self.listen: dict[str, list[dict[str, Any]]] = {}

    def body_objekt(self) -> dict[str, Any]:
        daten: dict[str, Any] = {"id": self.kennung, "type": f"{OPARL}Body", "name": self.name}
        for art in self.listen:
            daten[LISTENFELD.get(art, art)] = f"{self.adresse}/{art}"
        return daten

    def antwort(self, request: httpx.Request) -> httpx.Response | None:
        url = str(request.url).split("?", 1)[0]
        if url == self.adresse:
            return httpx.Response(200, json=self.body_objekt())
        for art, objekte in self.listen.items():
            if url == f"{self.adresse}/{art}":
                return httpx.Response(200, json={"data": objekte, "links": {}})
        return None


