class Bestand:
    """Zwei Quellen mit je einer Kommune; Stadt B hat von jeder Art ein Objekt im Bestand."""

    def __init__(self, storage: DatabaseStorage) -> None:
        self.storage = storage
        self.processor = OParlProcessor()
        self.kommune: dict[str, uuid.UUID] = {}
        self.quelle: dict[str, uuid.UUID] = {}

    async def kommune_anlegen(self, basis: str, quelle: str | None = None, nummer: int = 1) -> uuid.UUID:
        quelle = quelle or f"{basis}/system"
        source_id = await self.storage.upsert_source(quelle, quelle)
        kennung = f"{basis}/body/{nummer}"
        daten = {"id": kennung, "type": f"{OPARL}Body", "name": kennung, "paper": f"{kennung}/paper"}
        body_id = await self.storage.upsert_body(self.processor.process_body(daten, kennung), source_id)
        self.quelle[kennung] = source_id
        self.kommune[kennung] = body_id
        return body_id

    def verarbeitet(self, daten: dict[str, Any], kommune: str) -> Any:
        processed = self.processor.process(daten, kommune)
        assert processed is not None
        return processed

    async def schreiben(self, art: str, daten: dict[str, Any], body_id: uuid.UUID, kommune: str) -> Any:
        """Ein Objekt so schreiben, wie es ``_store_entity`` tut (Tagesordnungspunkte in eine Sitzung der Kommune)."""
        processed = self.verarbeitet(daten, kommune)
        storage = self.storage
        if art == "agendaitem":
            sitzung = await storage.get_meeting_uuid(processed.meeting_external_id, body_id)
            assert sitzung is not None
            return await storage.upsert_agenda_item(processed, sitzung)
        aufrufe: dict[str, Callable[..., Awaitable[Any]]] = {
            "paper": storage.upsert_paper,
            "meeting": storage.upsert_meeting,
            "person": storage.upsert_person,
            "organization": storage.upsert_organization,
            "membership": storage.upsert_membership,
            "location": storage.upsert_location,
            "file": storage.upsert_file,
            "consultation": storage.upsert_consultation,
            "legislativeterm": storage.upsert_legislative_term,
        }
        return await aufrufe[art](processed, body_id)

    async def stadt_b(self) -> None:
        body = await self.kommune_anlegen(B)
        for art, daten in ARTEN_B.items():
            await self.schreiben(art, daten(), body, KOMMUNE_B)


