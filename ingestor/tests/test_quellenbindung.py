async def _zeile(storage: DatabaseStorage, model: type, external_id: str) -> Any:
    async with storage.get_session() as session:
        return (await session.execute(select(model).where(model.external_id == external_id))).scalar_one_or_none()


async def _anzahl(storage: DatabaseStorage, sql: str, **parameter: Any) -> Any:
    async with storage.get_session() as session:
        return (await session.execute(text(sql), parameter)).scalar()


